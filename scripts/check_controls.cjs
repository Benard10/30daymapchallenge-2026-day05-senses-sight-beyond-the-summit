const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm'),assert=require('node:assert/strict');
const source=fs.readFileSync(path.join(__dirname,'../app.js'),'utf8');
const handlers={},controls={bearing:{value:'350'},radius:{value:'400'},curvature:{checked:true}};
for(const [id,control] of Object.entries(controls))control.addEventListener=(event,handler)=>{handlers[id]=handler;};
const state={bearing:350,radius:400,curved:true};
let reset=0,rebuild=false;
const updateText=()=>{controls.bearing.value=String(state.bearing);controls.radius.value=String(state.radius);};
const context={$:id=>controls[id],state,manual:()=>updateText(),coverage:{mark:()=>{}},inspectBeam:()=>{},updateText,resetScan:()=>reset++,schedule:value=>{rebuild=!!value;}};
const listeners=source.split('\n').filter(line=>/^\$\('(bearing|radius|curvature)'\)\.addEventListener/.test(line));
assert.equal(listeners.length,3);vm.runInNewContext(listeners.join('\n'),context);
controls.radius.value='700';handlers.radius({target:controls.radius});
assert.equal(state.radius,700,'Pausing must not overwrite the new distance before it is read');
assert.equal(controls.radius.value,'700');assert(rebuild);assert.equal(reset,1);
controls.bearing.value='123.25';handlers.bearing({target:controls.bearing});
assert.equal(state.bearing,123.25,'Pausing must not overwrite the new direction before it is read');
assert.equal(controls.bearing.value,'123.25');
controls.radius.value='1000';handlers.radius({target:controls.radius});assert.equal(state.radius,1000);
controls.curvature.checked=false;handlers.curvature({target:controls.curvature});assert.equal(state.curved,false);
console.log('Control regression checks passed: distance, direction, maximum range and curvature.');
